#!/usr/bin/env node
// Fetch separately, review the diff, then commit the generated rate card.
// Usage: node scripts/update-usage-prices.mjs /path/to/models.dev-api.json
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const path = process.argv[2];
if (!path) throw new Error('Expected a downloaded https://models.dev/api.json snapshot');
const bytes = readFileSync(path);
const catalog = JSON.parse(bytes.toString('utf8'));
const rates = {};
const rate = (value) => {
  if (!value || typeof value.input !== 'number' || typeof value.output !== 'number') return undefined;
  const result = {};
  for (const key of ['input', 'output', 'cache_read', 'cache_write']) {
    if (value[key] === undefined) continue;
    if (!Number.isFinite(value[key]) || value[key] < 0) throw new Error(`Invalid ${key} rate`);
    result[key] = value[key];
  }
  return result;
};
for (const providerId of ['openai', 'anthropic']) {
  for (const [modelId, model] of Object.entries(catalog[providerId].models).sort(([a], [b]) => a.localeCompare(b))) {
    if (model.modalities?.output?.length !== 1 || model.modalities.output[0] !== 'text') continue;
    const base = rate(model.cost);
    if (!base) continue;
    if (model.cost.reasoning !== undefined && model.cost.reasoning !== model.cost.output) {
      throw new Error(`Separate reasoning pricing needs review for ${providerId}/${modelId}`);
    }
    const tiers = (model.cost.tiers ?? []).map((entry) => {
      if (entry.tier?.type !== 'context' || !Number.isSafeInteger(entry.tier.size) || entry.tier.size <= 0) {
        throw new Error(`Unsupported pricing tier for ${providerId}/${modelId}`);
      }
      const tierRate = rate(entry);
      if (!tierRate) throw new Error(`Incomplete pricing tier for ${providerId}/${modelId}`);
      return { above: entry.tier.size, ...tierRate };
    });
    if (model.cost.context_over_200k && tiers.length === 0) {
      throw new Error(`Legacy context tier needs review for ${providerId}/${modelId}`);
    }
    rates[`${providerId}/${modelId}`] = { ...base, ...(tiers.length ? { tiers } : {}) };
  }
}
const snapshot = {
  source: 'https://models.dev/api.json',
  license: 'MIT; https://github.com/anomalyco/models.dev/blob/dev/LICENSE',
  capturedAt: new Date().toISOString(),
  sha256: createHash('sha256').update(bytes).digest('hex'),
};
