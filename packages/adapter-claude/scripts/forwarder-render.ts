/**
 * Forwarder renderer: src/generated/forwarder-source.ts is GENERATED from src/launch/forwarder.ts — the module is
 * canonical, this is the text a launch stages for a host that lends no forwarder runtime. Consumed by
 * generate-forwarder-source.mjs (CLI write) and src/generated/forwarder-source.test.ts (byte-parity freshness check).
 *
 * A transpile is the whole build: the forwarder imports Node's builtins only, so no bundler is needed, and its
 * output is one ES module plus a tail that runs it on its own arguments. Self-contained by design (the source text
 * is passed in): node type stripping executes this file from the .mjs CLI.
 */

import ts from 'typescript';

/** What makes the transpiled module a program: run the words on the process's own arguments. */
const TAIL = 'process.exitCode = await runClaudeForwarder(process.argv.slice(2));\n';

/** The staged forwarder: launch/forwarder.ts as one ES module, comments dropped, and its tail. */
export function renderForwarderModule(source: string): string {
  const { outputText } = ts.transpileModule(source, {
    fileName: 'forwarder.ts',
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      removeComments: true,
      newLine: ts.NewLineKind.LineFeed,
    },
  });
  return `${outputText}${TAIL}`;
}

/** src/generated/forwarder-source.ts: the staged forwarder as one string constant. */
export function renderForwarderSource(source: string): string {
  return [
    '/**',
    ' * GENERATED by scripts/generate-forwarder-source.mjs from src/launch/forwarder.ts. Do not hand-edit; run',
    ' * `pnpm --filter @vibefield/puppeteer-adapter-claude generate:forwarder`.',
    ' */',
    "// The string is the transpiler's output, byte for byte.",
    '// prettier-ignore',
    `export const CLAUDE_FORWARDER_SOURCE = ${JSON.stringify(renderForwarderModule(source))};`,
    '',
  ].join('\n');
}
