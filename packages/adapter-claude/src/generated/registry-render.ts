/**
 * Registry renderer (draft/EMULATOR.md §2, ADAPTING-AN-AGENT step 4):
 * registry.ts is GENERATED from the Surface-owned Claude model — the model is
 * canonical, this is the projection. Consumed by scripts/generate-registry.mjs
 * (CLI write) and src/generated/registry.test.ts (byte-parity freshness check).
 *
 * Self-contained by design (no runtime imports — the model is passed in):
 * node type stripping executes this file from the .mjs CLI, and node does not
 * remap `.js`-suffixed relative imports.
 *
 * Output is prettier-stable: every registry entry stays multiline (prettier
 * preserves objects whose `{` is followed by a newline), so regeneration is
 * byte-stable across `pnpm format` runs.
 */

import type { SurfaceModel } from '@vibecook/chopsticks-surface';

/** JS string literal using the quote with fewer escapes (Prettier style). */
function jsStr(value: string): string {
  const escapedBackslashes = value.replace(/\\/g, '\\\\');
  const singleEscapes = [...value].filter((character) => character === "'").length;
  const doubleEscapes = [...value].filter((character) => character === '"').length;
  return singleEscapes > doubleEscapes
    ? `"${escapedBackslashes.replace(/"/g, '\\"')}"`
    : `'${escapedBackslashes.replace(/'/g, "\\'")}'`;
}

export function renderRegistry(model: SurfaceModel): string {
  const version = model.manifest.vendorVersion;
  /** Prettier wraps a property whose line exceeds 120 columns as `key:` + indented value. */
  const prop = (key: string, value: string): string => {
    const inline = `    ${key}: ${value},`;
    return inline.length <= 120 ? inline : `    ${key}:\n      ${value},`;
  };
  const entries = model.events
    .map((event) => {
      const registration = event.resultSchema
        ? 'response-required'
        : event.matcherRequired
          ? 'matcher-required'
          : 'passive';
      const lines = [
        prop('event', jsStr(event.event)),
        prop('transport', jsStr(event.transport ?? '')),
        prop('registration', jsStr(registration)),
        prop('confidence', jsStr(event.confidence)),
        prop('timeoutSec', String(event.timeoutSec)),
      ];
      if (event.notes) lines.push(prop('notes', jsStr(event.notes)));
      return `  {\n${lines.join('\n')}\n  },`;
    })
    .join('\n');

  return `/**
 * GENERATED by scripts/generate-registry.mjs from
 * @vibecook/chopsticks-surface/vendors/claude/model/claude@${version}
 * — do not hand-edit. Edit the model and regenerate; the colocated registry test
 * enforces byte-parity.
 *
 * Claude Code hook-event registry — DATA, not code (DESIGN §16.5: settings
 * are generated from a registry, never handwritten; §10: capability-probe,
 * don't assume).
 *
 * Ground truth: the claim-addressable Surface candidate for Claude Code
 * ${version}. Runtime-captured and official-document-only events remain
 * visibly distinct through their confidence values.
 *
 * Transport preference implements the hybrid bridge (DESIGN §16.4):
 * high-frequency events go over HTTP (no forwarder process per event);
 * low-frequency lifecycle events tolerate the command forwarder, which is
 * also the fallback if a probe finds an event type without HTTP support.
 */

export type HookTransport = 'http' | 'command';

export type HookRegistration = 'passive' | 'matcher-required' | 'response-required';

export type HookConfidence =
  | 'verified-headless' // fired in \`-p\` runs A–F
  | 'verified-interactive' // fired only under the M1 PTY census
  | 'unverified'; // name known (spaghetti HookEventName union); never observed

export interface HookEventSpec {
  /** Claude Code \`hook_event_name\`. */
  event: string;
  transport: HookTransport;
  /** Whether registration is passive, needs a matcher, or must produce a native result. */
  registration: HookRegistration;
  confidence: HookConfidence;
  /** Hook timeout written into generated settings. */
  timeoutSec: number;
  /** Payload fields beyond the common envelope that the normalizer relies on. */
  notes?: string;
}

export const CLAUDE_SURFACE_VERSION = ${jsStr(version)} as const;

export const CLAUDE_HOOK_REGISTRY: readonly HookEventSpec[] = [
${entries}
];

export function getHookSpec(event: string): HookEventSpec | undefined {
  return CLAUDE_HOOK_REGISTRY.find((s) => s.event === event);
}

/** Events observed at least once on a real session, independent of registration semantics. */
export function verifiedHookEvents(): HookEventSpec[] {
  return CLAUDE_HOOK_REGISTRY.filter((s) => s.confidence !== 'unverified');
}

/** Events whose empty response preserves Claude Code's native behavior. */
export function defaultHookEvents(): HookEventSpec[] {
  return CLAUDE_HOOK_REGISTRY.filter((s) => s.registration === 'passive');
}

/** Every event the pinned official reference declares for this release. */
export function supportedHookEvents(): HookEventSpec[] {
  return [...CLAUDE_HOOK_REGISTRY];
}
`;
}

/** Render a small adapter-local projection of the Surface-owned detection document. */
export function renderDetectionSurface(document: unknown): string {
  return `/**
 * GENERATED by scripts/generate-registry.mjs from the Surface-owned Claude
 * detection document. Do not hand-edit; regenerate adapter projections.
 */
// JSON formatting is part of the deterministic generated projection.
// prettier-ignore
export const CLAUDE_DETECTION_SURFACE = ${JSON.stringify(document, null, 2)} as const;
`;
}
